export function getListingBySlug(slug: string): Listing | undefined {
  return listings.find((l) => l.slug === slug)
}

export function getListingsByCategory(categorySlug: string): Listing[] {
  return listings.filter((l) => l.categorySlug === categorySlug)
}

export function getListingsByCity(citySlug: string): Listing[] {
  return listings.filter((l) => l.citySlug === citySlug)
}

export function getListingsByCategoryAndCity(categorySlug: string, citySlug: string): Listing[] {
  return listings.filter((l) => l.categorySlug === categorySlug && l.citySlug === citySlug)
}

export function getFeaturedListings(): Listing[] {
  return listings
    .filter((l) => l.featured)
    .sort((a, b) => b.qualityScore - a.qualityScore)
}
